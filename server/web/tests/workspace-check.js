// 真实 API 测试：临时库、本地端口、一次性开发验证码。
import assert from 'node:assert/strict'
import { mkdtemp, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { chromium } from 'playwright'
import { checkLiveObservation } from './observe-live.js'
import { createServer } from '../../src/server.ts'
import { seedTenant } from '../../src/seed.ts'
import { MemoryPresence } from '../../src/presence.ts'

const dir = await mkdtemp(join(tmpdir(), 'onex-web-test-'))
const target = 'owner@example.test'
let code
const app = await createServer({ dataDir: dir, hostname: '127.0.0.1', port: 0, heartbeatMs: 15000,
  tenantCacheSize: 2, presence: new MemoryPresence(), commit: 'test', codeSecret: crypto.randomUUID(), masterKey: crypto.getRandomValues(new Uint8Array(32)),
  deliverCode: (_, value) => { code = value } })
const browser = await chromium.launch({ channel: 'chrome', args: ['--disable-gpu'] })
try {
  const seed = await seedTenant(app.store, { target, name: '联调租户', platformAdmin: true })
  const page = await browser.newPage({ baseURL:app.server.url.href, viewport: { width: 1280, height: 720 } })
  page.setDefaultTimeout(3500)
  const summaryOnly=process.argv.includes('--summary-only')
  const shots = process.argv.slice(2).find(a=>a!=='--summary-only')
  async function capture(label) {
    if (!shots) return
    for (const [width,height] of [[1280,720],[1440,900]]) {
      await page.setViewportSize({width,height})
      const r=await page.evaluate(async label=>(await import('/tests/layout-check.js')).runLayoutChecks(label),label)
      assert(r.pass, JSON.stringify(r.checks.filter(c=>!c.pass)))
      await page.evaluate(() => new Promise(done => requestAnimationFrame(() => requestAnimationFrame(done))))
      await page.screenshot({path:join(shots,`${width}x${height}-${label}.png`), fullPage:true})
    }
  }
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.route('**/*', async route => {
    const path = new URL(route.request().url()).pathname
    if (path.startsWith('/v1/')) return route.continue()
    const file = Bun.file(new URL('..' + (path === '/' ? '/index.html' : path), import.meta.url))
    return route.fulfill({ status: await file.exists() ? 200 : 404, contentType: file.type, body: await file.exists() ? await file.text() : '' })
  })
  const button = name => page.getByRole('button', { name, exact: true })
  const link = name => page.getByRole('link', { name, exact: true })
  const field = name => page.locator(`[name="${name}"]`)
  await page.goto(app.server.url.href)
  await page.getByPlaceholder('邮箱或手机号').fill(target)
  await button('发送验证码').click()
  await page.getByText('验证码已发送，请查收').waitFor()
  await page.getByPlaceholder('6 位验证码').fill(code)
  await button('登录').click()
  await page.locator('tr.clickable').waitFor()
  await page.getByRole('combobox',{name:'状态'}).selectOption('disabled')
  await page.getByText('没有成员',{exact:true}).waitFor()
  await page.getByRole('combobox',{name:'状态'}).selectOption('')
  await page.getByRole('combobox',{name:'角色'}).selectOption('member')
  await page.getByText('没有成员',{exact:true}).waitFor()
  await link('分组').click()
  await button('新建分组').click()
  await field('name').fill('研发组')
  await button('保存').click()
  await page.locator('tr.clickable').getByText('研发组').waitFor()
  await capture('groups-real')
  await link('成员').click()
  await button('生成邀请码').click()
  await button('生成').click()
  const invite = await page.getByLabel('一次性邀请码').inputValue()
  assert(invite.length > 16)
  await button('← 返回').click()
  assert.equal(await page.getByLabel('一次性邀请码').count(), 0)
  assert(!await page.evaluate(v => JSON.stringify(localStorage).includes(v), invite))
  await link('平台').click()
  await button('新建 Provider').click()
  await field('name').fill('测试渠道')
  await field('base_url').fill('http://127.0.0.1:9999')
  await field('secret').fill('fixture-only')
  await button('保存').click()
  await page.getByText('测试渠道', { exact: true }).click()
  await page.getByText('已设置', { exact: true }).waitFor()
  assert.equal(await page.getByText('fixture-only').count(), 0)
  await button('模型目录').click()
  await button('新建模型').click()
  await field('upstream_name').fill('test-model')
  await field('display_name').fill('联调模型')
  await field('context_window').fill('4096')
  await button('保存').click()
  await page.getByText('联调模型', { exact: true }).click()
  await button('倍率记录').click()
  await button('新建倍率').click()
  await field('input_milli_per_mtok').fill('0.015')
  await button('保存').click()
  await page.locator('.table-scroll').last().getByText('0.015', { exact: true }).waitFor()
  await capture('pricing-real')
  await link('合约模板').click()
  await button('发布新模板').click()
  await field('id').fill('workspace')
  await field('name').fill('联调模板')
  await field('seat_limit').fill('19')
  await field('lease_minutes').fill('10')
  await field('lease_blocks').fill('2.5')
  await field('admin_content').selectOption(summaryOnly ? 'false' : 'true')
  await page.getByRole('checkbox', { name: 'Claude Code', exact: true }).check()
  await page.getByRole('checkbox', { name: /联调模型/ }).check()
  await button('发布模板').click()
  await page.getByText('模板权益', { exact: true }).waitFor()
  await link('平台合约').click()
  await page.locator('tr.clickable').getByText('联调租户', { exact: true }).click()
  await button('签发合约').click()
  assert.equal(await field('lease_blocks').inputValue(), '2.5')
  await page.getByLabel('签发原因').fill('联调签发')
  assert.equal(await button('发布').isDisabled(), true)
  await button('预览变更').click()
  await page.getByText('发布后生效', { exact: true }).waitFor()
  await button('发布').click()
  await button('签发历史').click()
  await page.locator('tr.clickable').getByText('联调签发', { exact: true }).click()
  await page.getByText('平台合约第 1 版', { exact: true }).waitFor()
  await link('租户').click()
  await link('合约').click()
  await button('编辑租户配置').click()
  await page.getByLabel('管理员查看正文').selectOption('')
  await page.getByLabel('组管查看摘要').selectOption('false')
  await page.getByLabel('租约额度（块）').fill('0.0005')
  await button('预览变更').click()
  await page.getByText('租约额度须为不小于 0 的块数，精确到 0.001 块').waitFor()
  await page.getByLabel('租约额度（块）').fill('1.125')
  await page.getByLabel('模型配置方式').selectOption('inherit')
  await button('预览变更').click()
  await page.getByText('发布后生效', { exact: true }).waitFor()
  await capture('contract-real')
  await button('发布').click()
  await page.getByText('平台合约第 1 版 · 租户配置第 2 版').waitFor()
  assert.equal(app.store.tenant(seed.tenantId).get('SELECT lease_budget_milli FROM contract ORDER BY revision DESC LIMIT 1').lease_budget_milli, 1125)
  await link('橡皮').click()
  await button('充值').click()
  await field('amount').fill('2.075')
  await button('确认充值').click()
  await page.getByText('2.075', {exact:true}).first().waitFor()
  await page.locator('tr').getByText('充值',{exact:true}).waitFor()
  await capture('billing-real')
  const staff = 'staff@example.test', admin = 'admin@example.test'
  const roles = () => field('role').locator('option').evaluateAll(opts => opts.map(o => o.value).sort())
  await page.request.post('/v1/auth/code', {data:{target:staff}})
  assert((await page.request.post('/v1/auth/login', {data:{target:staff,code,invite_code:invite}})).ok())
  await link('成员').click()
  const staffRow = page.locator('tr.clickable').filter({hasText:staff})
  await staffRow.click()
  await button('编辑').click()
  await field('role').waitFor()
  assert.deepEqual(await roles(), ['admin','group_admin','member'])
  await button('← 返回').click()
  await button('生成邀请码').click()
  assert.deepEqual(await roles(), ['admin','group_admin','member'])
  await field('role').selectOption('admin')
  await button('生成').click()
  const adminInvite = await page.getByLabel('一次性邀请码').inputValue()
  await page.locator('.account-menu summary').click()
  await button('退出').click()
  await button('邀请码登录').click()
  await page.getByPlaceholder('邮箱或手机号').fill(admin)
  await page.getByPlaceholder('邀请码',{exact:true}).fill(adminInvite)
  await button('发送验证码').click()
  await page.getByText('验证码已发送，请查收').waitFor()
  await page.getByPlaceholder('6 位验证码').fill(code)
  await button('登录').click()
  await staffRow.click()
  await button('编辑').click()
  await field('role').waitFor()
  assert.deepEqual(await roles(), ['member'])
  await button('← 返回').click()
  await button('生成邀请码').click()
  assert.deepEqual(await roles(), ['member'])
  await link('合约').click()
  const currentClause = label => page.locator('.contract-comparison tr').filter({ has: page.getByRole('rowheader', { name: label, exact: true }) }).locator('td').last()
  assert.equal(await currentClause('管理员查看正文').innerText(), summaryOnly ? '关闭' : '允许')
  assert.equal(await currentClause('组管查看摘要').innerText(), '关闭')
  assert.equal(await button('编辑租户配置').count(), 0)
  await checkLiveObservation({app,seed,page,target,capture,summaryOnly})
  assert.deepEqual(errors, [])
  console.log('真实 Server：登录、成员筛选、分组、邀请码、平台目录、倍率、租户合约和充值通过')
} finally {
  await browser.close()
  await app.close()
  await rm(dir, { recursive: true, force: true })
}
